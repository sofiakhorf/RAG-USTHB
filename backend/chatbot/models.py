
import uuid

from django.conf import settings
from django.db import models


class StudentProfile(models.Model):
    """Additional information collected from the student signup form."""

    DEPARTMENTS = [
        ("computer_science", "Computer Science"),
        ("mathematics", "Mathematics"),
        ("physics", "Physics"),
        ("chemistry", "Chemistry"),
        ("electronics", "Electronics"),
        ("civil_engineering", "Civil Engineering"),
    ]

    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False,
    )

    user = models.OneToOneField(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="student_profile",
    )

    matricule = models.CharField(max_length=30, unique=True)
    department = models.CharField(max_length=50, choices=DEPARTMENTS)
    role = models.CharField(
        max_length=20,
        choices=[
            ("student", "Student"),
            ("admin", "Admin"),
        ],
        default="student",
    )

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return f"{self.matricule} - {self.user.email}"


class Document(models.Model):
    """A university document available in the shared knowledge base."""

    STATUS_CHOICES = [
        ("uploaded", "Uploaded"),
        ("processing", "Processing"),
        ("processed", "Processed"),
        ("failed", "Failed"),
    ]

    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False,
    )

    title = models.CharField(max_length=255)
    original_filename = models.CharField(max_length=255)
    stored_path = models.CharField(max_length=500, blank=True)
    file_hash = models.CharField(max_length=128, blank=True, db_index=True)

    family_type = models.CharField(max_length=100, blank=True)
    mime_type = models.CharField(max_length=100, blank=True)
    size_bytes = models.PositiveBigIntegerField(null=True, blank=True)

    status = models.CharField(
        max_length=20,
        choices=STATUS_CHOICES,
        default="uploaded",
    )
    error_message = models.TextField(blank=True)
    metadata = models.JSONField(default=dict, blank=True)

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return self.title


class Chunk(models.Model):
    """A text segment extracted from a university document."""

    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False,
    )

    # Stable ID generated by the existing ingestion pipeline.
    chunk_id = models.CharField(max_length=32, unique=True)

    document = models.ForeignKey(
        Document,
        on_delete=models.CASCADE,
        related_name="chunks",
    )
    chunk_index = models.PositiveIntegerField(default=0)
    text = models.TextField()

    # Metadata fields used by the existing RAG pipeline.
    document_name = models.CharField(max_length=255, blank=True)
    family_type = models.CharField(max_length=100, blank=True)
    procedure = models.CharField(max_length=255, blank=True)
    formation = models.CharField(max_length=255, blank=True)
    niveau = models.CharField(max_length=100, blank=True)
    semestre = models.CharField(max_length=100, blank=True)
    ue = models.CharField(max_length=255, blank=True)
    matiere = models.CharField(max_length=255, blank=True)
    annee_universitaire = models.CharField(max_length=50, blank=True)
    page = models.PositiveIntegerField(null=True, blank=True)
    sheet_name = models.CharField(max_length=255, blank=True)
    block_range = models.CharField(max_length=255, blank=True)
    block_title = models.CharField(max_length=255, blank=True)
    chapter = models.CharField(max_length=255, blank=True)
    article_title = models.CharField(max_length=255, blank=True)
    article_number = models.CharField(max_length=100, blank=True)
    language = models.CharField(max_length=20, blank=True)
    is_fallback = models.BooleanField(default=False)
    metadata = models.JSONField(default=dict, blank=True)

    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        constraints = [
            models.UniqueConstraint(
                fields=["document", "chunk_index"],
                name="unique_chunk_index_per_document",
            )
        ]
        indexes = [
            models.Index(fields=["document", "chunk_index"]),
            models.Index(fields=["family_type"]),
            models.Index(fields=["matiere"]),
        ]

    def __str__(self):
        return f"{self.document.title} - Chunk {self.chunk_index}"


class Embedding(models.Model):
    """Vector representation of a chunk."""

    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False,
    )

    chunk = models.OneToOneField(
        Chunk,
        on_delete=models.CASCADE,
        related_name="embedding",
    )

    # Portable storage for now. Use pgvector VectorField( dimensions=384 )
    # after configuring PostgreSQL and installing pgvector.
    embedding = models.JSONField(default=list)
    model_name = models.CharField(max_length=150)
    dimensions = models.PositiveIntegerField(default=384)

    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"Embedding for {self.chunk.chunk_id}"


class ChatSession(models.Model):
    """One conversation belonging to a student."""

    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False,
    )

    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="rag_chat_sessions",
    )
    title = models.CharField(max_length=255, default="New conversation")

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return self.title


class ChatMessage(models.Model):
    """A user's question or an assistant's response."""

    ROLES = [
        ("user", "User"),
        ("assistant", "Assistant"),
        ("system", "System"),
    ]

    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False,
    )

    session = models.ForeignKey(
        ChatSession,
        on_delete=models.CASCADE,
        related_name="messages",
    )
    role = models.CharField(max_length=20, choices=ROLES)
    content = models.TextField()

    # IDs of the chunks used to generate the answer.
    # These are Chunk.id UUIDs, not Chunk.chunk_id strings.
    context_chunks = models.JSONField(default=list, blank=True)

    # Source information displayed alongside the answer.
    sources = models.JSONField(default=list, blank=True)

    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["created_at"]

    def __str__(self):
        return f"{self.role} - {self.session_id}"
